// Bundles WLED Studio into a self-contained HTML file (dist/index.html) plus the Glow
// compiler/VM bundle loaded on demand by the Scripts page (dist/studio-glow.js);
// --header gzips both into wled00/html_studio.h.
// Usage: node studio/build.mjs [--dev]  (exports buildHtml() for the dev server)
import * as esbuild from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = dirname(fileURLToPath(import.meta.url));

function genExamples() {
  const ex = join(dir, '..', 'glow', 'examples');
  const list = readdirSync(ex).filter(f => f.endsWith('.glow')).sort().map(f => {
    const src = readFileSync(join(ex, f), 'utf8');
    const name = /(?:effect|show)\s+"([^"]+)"/.exec(src)?.[1] ?? f;
    return { file: f.replace(/\.glow$/, ''), name, src };
  });
  writeFileSync(join(dir, 'src', 'examples.gen.js'), `// generated by studio/build.mjs\nexport default ${JSON.stringify(list, null, 1)};\n`);
}

export async function buildHtml({ dev = false } = {}) {
  genExamples();
  const js = await esbuild.build({
    entryPoints: [join(dir, 'src', 'main.jsx')], bundle: true, format: 'iife', write: false,
    jsx: 'automatic', jsxImportSource: 'preact', define: { 'process.env.NODE_ENV': dev ? '"development"' : '"production"' },
    minify: !dev, sourcemap: dev ? 'inline' : false, target: ['es2020', 'safari14'], legalComments: 'none',
  });
  const css = await esbuild.build({ entryPoints: [join(dir, 'src', 'styles.css')], bundle: true, write: false, minify: !dev, loader: { '.css': 'css' } });
  const html = readFileSync(join(dir, 'index.html'), 'utf8')
    .replace(/<link rel="stylesheet"[^>]*>/, () => `<style>${css.outputFiles[0].text}</style>`)
    .replace(/<script type="module" src="[^"]*"><\/script>/, () => `<script>${js.outputFiles[0].text.replace(/<\/script/g, '<\\/script')}</script>`);
  return html;
}

export async function buildGlow({ dev = false } = {}) {
  const js = await esbuild.build({
    entryPoints: [join(dir, 'src', 'glow-entry.js')], bundle: true, format: 'iife', write: false,
    minify: !dev, sourcemap: dev ? 'inline' : false, target: ['es2020', 'safari14'], legalComments: 'none',
  });
  return js.outputFiles[0].text;
}

const cArray = (name, gz) => {
  const hexs = [...gz].map(b => `0x${b.toString(16).padStart(2, '0')}`);
  const rows = []; for (let i = 0; i < hexs.length; i += 20) rows.push('  ' + hexs.slice(i, i + 20).join(', '));
  return `const uint32_t ${name}_length = ${gz.length};\nconst uint8_t ${name}[] PROGMEM = {\n${rows.join(',\n')}\n};\n`;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dev = process.argv.includes('--dev');
  const [html, glow] = await Promise.all([buildHtml({ dev }), buildGlow({ dev })]);
  mkdirSync(join(dir, 'dist'), { recursive: true });
  writeFileSync(join(dir, 'dist', 'index.html'), html);
  writeFileSync(join(dir, 'dist', 'studio-glow.js'), glow);
  const { gzipSync } = await import('node:zlib');
  const gz = gzipSync(html, { level: 9 }), gzGlow = gzipSync(glow, { level: 9 });
  console.log(`studio/dist/index.html: ${(html.length / 1024).toFixed(1)} KB, gzip ${(gz.length / 1024).toFixed(1)} KB`);
  console.log(`studio/dist/studio-glow.js: ${(glow.length / 1024).toFixed(1)} KB, gzip ${(gzGlow.length / 1024).toFixed(1)} KB (loaded by the Scripts page)`);
  if (process.argv.includes('--header')) {
    const hash = createHash('sha1').update(gz).update(gzGlow).digest('hex').slice(0, 8);
    writeFileSync(join(dir, '..', 'wled00', 'html_studio.h'),
      `/*\n * WLED Studio UI — generated by studio/build.mjs, do not edit.\n */\n#pragma once\n\n` +
      `// content hash, mixed into the HTTP ETag so browsers fetch a new UI after a firmware update\n` +
      `#define STUDIO_BUILD_HASH 0x${hash}u\n` + cArray('PAGE_studio', gz) + cArray('JS_studio_glow', gzGlow));
    console.log('wrote wled00/html_studio.h');
  }
}
